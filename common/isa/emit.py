"""Assembly emission for the six targets.

The emitter turns a validated SIMT IR program into assembly text for the target
toolchain.  Target differences are *data* (``common/isa/<target>.json``):

* ``dialect``      -- currently ``riscv`` (four targets) or ``opaque`` (the
                      target's own assembler is invoked on the same text)
* ``macros``       -- the ``GPU_*`` macro bodies for operations that only exist as
                      target specific instructions (barrier, texture, cache
                      control, saturating arithmetic, thread-id CSRs, ...)
* ``toolchain``    -- assembler/linker/objcopy commands

Register contract (identical for every target):

    r0 = x0 zero      r1 = x1 thread id     r2 = x2 stack pointer (macros only)
    r5..r12  = template registers, kernel ABI scratch
    r13..r31 = program scratch

A ``GPU_*`` macro must not clobber x1 or x5..x31; it may spill through x2/sp.
Operations without a macro are reported as *unsupported* instead of being
silently mis-compiled, and :mod:`adapters.doctor` surfaces them per target.
"""
from __future__ import annotations

import os
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional, Sequence, Set, Tuple

from common.ir import Instr, MemRef, Program
from common.targets import TargetSpec, load_target
from common.util import read_json, write_json

# IR op -> (macro, direct mnemonic, feature)  -- riscv dialect
DIRECT = {
    "add": "add", "sub": "sub", "and": "and", "or": "or", "xor": "xor",
    "shl": "sll", "shr": "srl", "sra": "sra", "slt": "slt", "sltu": "sltu",
    "mul": "mul", "mulh": "mulh", "div": "div", "rem": "rem", "mov": "mv",
    "fence": "fence", "nop": "nop", "la": "la", "jmp": "j", "jmp_reg": "jr",
    "mov_imm": "li",
}
# ops that go through a target macro even on riscv (no base-ISA equivalent)
MACRO_OPS = {
    "tid": "GPU_GET_TID", "laneid": "GPU_GET_LANEID", "warpid": "GPU_GET_WARPID",
    "ctaid": "GPU_GET_CTAID", "ntid": "GPU_GET_NTID", "nctaid": "GPU_GET_NCTAID",
    "clock": "GPU_GET_CLOCK",
    "min": "GPU_MIN", "max": "GPU_MAX", "abs": "GPU_ABS", "neg": "GPU_NEG",
    "mad": "GPU_MAD", "sat_add": "GPU_SAT_ADD", "sat_sub": "GPU_SAT_SUB",
    "fadd": "GPU_FADD", "fsub": "GPU_FSUB", "fmul": "GPU_FMUL", "fdiv": "GPU_FDIV",
    "f2i": "GPU_F2I", "i2f": "GPU_I2F", "fneg": "GPU_FNEG", "fabs": "GPU_FABS",
    "fcvt_rtz": "GPU_FCVT_RTZ", "fcvt_rup": "GPU_FCVT_RUP",
    "fcvt_rdn": "GPU_FCVT_RDN", "fcvt_rne": "GPU_FCVT_RNE",
    "tex": "GPU_TEX", "cache_op": "GPU_CACHE_OP", "getcfg": "GPU_GETCFG",
    "setcfg": "GPU_SETCFG", "memcpy_len": "GPU_DMA",
    "bar": "GPU_BARRIER", "exit": "GPU_EXIT", "fence": "GPU_FENCE",
}
MEM_DIRECT = {("global", 4): "lw", ("global", 2): "lh", ("global", 1): "lb"}
MEM_STORE = {("global", 4): "sw", ("global", 2): "sh", ("global", 1): "sb"}


@dataclass
class EmitResult:
    asm: str = ""
    macros_used: List[str] = field(default_factory=list)
    macros_missing: List[str] = field(default_factory=list)
    unsupported: List[str] = field(default_factory=list)
    notes: List[str] = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return not self.unsupported

    def macro_header(self, profile: Dict[str, Any]) -> str:
        """Emit the ``.macro`` definitions this program needs."""
        defs = profile.get("macros") or {}
        out = ["# GPU macro definitions generated by GPUFuzz"]
        for name in self.macros_used:
            spec = defs.get(name)
            if not spec:
                out.append("# MISSING MACRO %s -- provide it in the target profile" % name)
                continue
            args = spec.get("args", ["rd"] + ["rs%d" % (i + 1) for i in range(spec.get("nargs", 0) - 1)])
            body = spec.get("body") or []
            out.append(".macro %s %s" % (name, ", ".join(args)))
            for line in body:
                out.append("    " + line)
            out.append(".endm")
            if spec.get("conf") and spec["conf"] != "high":
                out.append("# confidence=%s %s" % (spec["conf"], spec.get("note", "")))
        return "\n".join(out)


class AssemblyEmitter:
    def __init__(self, profile: Dict[str, Any], symbol: Optional[str] = None) -> None:
        self.profile = profile
        self.symbol = symbol or profile.get("entry", "gpufuzz_entry")

    # ------------------------------------------------------------------ #
    @staticmethod
    def hw_reg(ir_reg: str) -> str:
        """IR register name -> hardware register (identity for every target)."""
        return "x" + ir_reg[1:]

    def emit(self, prog: Program) -> EmitResult:
        res = EmitResult()
        dialect = self.profile.get("dialect", "riscv")
        lines: List[str] = []
        lines.append("# generated by GPUFuzz: %s (%s), %d instructions"
                     % (self.profile.get("target", "?"), dialect, len(prog)))
        lines.append(".text")
        lines.append(".globl %s" % self.symbol)
        lines.append("%s:" % self.symbol)

        for idx, ins in enumerate(prog.instrs):
            try:
                out = self._insn(ins, res)
            except KeyError as exc:
                res.unsupported.append("insn %d (%s): %s" % (idx, ins.op, exc))
                out = ["# UNSUPPORTED: %s" % ins.text()]
            if out:
                lines.append("    " + out[0])
                lines.extend("    " + l for l in out[1:])
        lines.append("")
        res.asm = "\n".join(lines)
        res.notes.append("entry symbol: %s" % self.symbol)
        return res

    # ------------------------------------------------------------------ #
    def _insn(self, ins: Instr, res: EmitResult) -> List[str]:
        op = ins.op
        if op == "label":
            return ["%s:" % ins.label]
        if op == "exit":
            return [self._macro("GPU_EXIT", [], res, nargs=0, quoted=True)]
        if op == "br":
            rs = self.hw_reg(ins.srcs[0])
            sense = ins.aux.get("sense", "nz")
            return ["%s %s, %s" % ("bnez" if sense == "nz" else "beqz", rs, ins.label)]
        if op == "jmp":
            return ["j %s" % ins.label]
        if op == "jmp_reg":
            return ["jr %s" % self.hw_reg(ins.srcs[0])]
        if op == "la":
            return ["la %s, %s" % (self.hw_reg(ins.dst), ins.label)]
        if op == "spin":
            lbl = ".Lspin%d" % id(ins)
            return ["li x5, %d" % max(1, ins.imm), "%s:" % lbl, "addi x5, x5, -1",
                    "bnez x5, %s" % lbl]
        if op in ("ld", "st"):
            return [self._mem(ins)]
        if op in MACRO_OPS:
            macro = MACRO_OPS[op]
            args = ([self.hw_reg(ins.dst)] if ins.dst else [])
            args += [self.hw_reg(s) for s in ins.srcs if isinstance(s, str)]
            if op == "bar":
                args = [str(ins.imm)]
            elif op == "cache_op":
                args = [str(ins.imm)] + args
            elif op in ("getcfg", "setcfg"):
                args = ['"%s"' % ins.aux.get("name", "cfg0")] + args
            elif op in ("tid", "laneid", "warpid", "ctaid", "ntid", "nctaid", "clock"):
                args = args[:1]
            elif op in ("fadd", "fsub", "fmul", "fdiv", "mad"):
                args = args[:3]
            return [self._macro(macro, args, res, nargs=len(args))]
        if op in DIRECT:
            mnem = DIRECT[op]
            if op in ("mov_imm",):
                return ["li %s, %d" % (self.hw_reg(ins.dst), ins.imm & 0xFFFFFFFF)]
            if op in ("mov",):
                return ["mv %s, %s" % (self.hw_reg(ins.dst), self.hw_reg(ins.srcs[0]))]
            dst = self.hw_reg(ins.dst) if ins.dst else ""
            args = [self.hw_reg(s) for s in ins.srcs if isinstance(s, str)]
            if op.startswith("f") or op in ("mad",):
                pass
            if op == "nop":
                return ["nop"]
            if op == "fence":
                return ["fence"]
            return ["%s %s" % (mnem, ", ".join([dst] + args)) if dst else "%s %s" % (mnem, ", ".join(args))]
        if op in ("fneg", "fabs"):
            macro = MACRO_OPS[op]
            return [self._macro(macro, [self.hw_reg(ins.dst), self.hw_reg(ins.srcs[0])],
                                res, nargs=2)]
        res.unsupported.append("op %r has no lowering" % (op,))
        return ["# UNSUPPORTED: %s" % ins.text()]

    def _mem(self, ins: Instr) -> str:
        m = ins.mem or MemRef()
        base = self.hw_reg(m.base) if m.base else "x0"
        off = m.offset
        addr = "%d(%s)" % (off, base) if off else "0(%s)" % base
        if m.space == "shared":
            macro = "GPU_LDS" if ins.op == "ld" else "GPU_STS"
            args = ([self.hw_reg(ins.dst)] if ins.op == "ld" else [self.hw_reg(ins.srcs[0])])
            return "%s %s, %d(%s)" % (macro, ", ".join(args), off, base)
        table = MEM_DIRECT if ins.op == "ld" else MEM_STORE
        mnem = table.get((m.space, m.width))
        if mnem is None:
            raise KeyError("no %s/%d lowering" % (m.space, m.width))
        if ins.op == "ld":
            return "%s %s, %s" % (mnem, self.hw_reg(ins.dst), addr)
        return "%s %s, %s" % (mnem, self.hw_reg(ins.srcs[0]), addr)

    def _macro(self, name: str, args: Sequence[str], res: EmitResult,
               nargs: int = 1, quoted: bool = False) -> str:
        if name not in res.macros_used:
            res.macros_used.append(name)
        if name not in (self.profile.get("macros") or {}):
            if name not in res.macros_missing:
                res.macros_missing.append(name)
            res.unsupported.append("macro %s is not defined for %s"
                                   % (name, self.profile.get("target", "?")))
            return "# UNSUPPORTED macro %s" % name
        return "%s %s" % (name, ", ".join(args))


