def profile_path(target: str) -> str:
    return os.path.join(os.path.dirname(os.path.abspath(__file__)), target + ".json")


def load_profile(target: str) -> Dict[str, Any]:
    p = read_json(profile_path(target))
    if p is None:
        raise FileNotFoundError("no ISA profile for %r (%s)" % (target, profile_path(target)))
    return p


def emit_program(prog: Program, target: str, symbol: Optional[str] = None) -> EmitResult:
    profile = load_profile(target)
    return AssemblyEmitter(profile, symbol).emit(prog)


def write_assembly(prog: Program, target: str, outdir: str, stem: str = "kernel") -> Dict[str, str]:
    """Write ``kernel.S``, ``macros.S`` and a ``toolchain.json`` for one test."""
    profile = load_profile(target)
    res = emit_program(prog, target)
    os.makedirs(outdir, exist_ok=True)
    paths = {}
    asm_path = os.path.join(outdir, stem + ".S")
    with open(asm_path, "w", encoding="utf-8") as fh:
        fh.write(".include \"macros.S\"\n")
        fh.write(res.asm)
    paths["asm"] = asm_path
    mac_path = os.path.join(outdir, "macros.S")
    with open(mac_path, "w", encoding="utf-8") as fh:
        fh.write(res.macro_header(profile) + "\n")
    paths["macros"] = mac_path
    start = os.path.join(outdir, "startup.S")
    with open(start, "w", encoding="utf-8") as fh:
        fh.write(_startup(profile))
    paths["startup"] = start
    paths["entry"] = profile.get("entry", "gpufuzz_entry")
    paths["toolchain"] = profile.get("toolchain", {})
    paths["unsupported"] = "; ".join(res.unsupported)
    write_json(os.path.join(outdir, "emit.json"),
               {"target": target, "entry": paths["entry"],
                "macros": res.macros_used, "missing": res.macros_missing,
                "unsupported": res.unsupported, "notes": res.notes})
    return paths


def _startup(profile: Dict[str, Any]) -> str:
    """Minimal bare-metal entry: set the stack pointer, call the kernel, exit."""
    startup = profile.get("startup") or {}
    lines = [
        "# startup stub generated by GPUFuzz",
        "# adjust the section/label names to the target's linker script",
        ".section .text.start",
        ".globl _start",
        "_start:",
        "    la sp, %s" % startup.get("stack", "__stack_top"),
        "    call %s" % profile.get("entry", "gpufuzz_entry"),
        "    GPU_EXIT",
        ".section .bss",
        ".align 4",
        "__stack_top:",
        "    .space %d" % int(startup.get("stack_bytes", 4096)),
    ]
    return "\n".join(lines) + "\n"
